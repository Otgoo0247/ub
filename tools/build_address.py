ABC = 'АБВГДЕЁЖЗИЙКЛМНОӨПРСТУҮФХЦЧШЩЪЫЬЭЮЯ'
def mn(w):  # Монгол цагаан толгойн дараалал (Ө, Ү зөв байрлалд)
    return [ABC.find(ch) if ch in ABC else (-1 if ch in ' -' else 100 + ord(ch)) for ch in w.upper()]


city = {}
with open(HERE.parent / 'public' / 'data' / 'khoroo.csv', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        city.setdefault(r['district'], []).append((int(r['khoroo_no']), r['khoroo']))
data = {
    'city': {'name': 'Улаанбаатар', 'districts': {d: [n for _, n in sorted(v)] for d, v in sorted(city.items(), key=lambda kv: mn(kv[0]))}},
    'aimags': {a: sorted((s.replace('_', ' ') for s in v.split()), key=mn) for a, v in sorted(AIMAG.items(), key=lambda kv: mn(kv[0]))},
}
for p in (HERE.parent / 'api' / '_lib' / 'address.json', HERE.parent / 'public' / 'js' / 'invite-address.json'):
    p.write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
